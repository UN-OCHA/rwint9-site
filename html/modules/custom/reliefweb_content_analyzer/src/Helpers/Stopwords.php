  /**
   * Build a lookup set of stopwords for the given language codes.
   *
   * Unknown codes are ignored. Empty input defaults to English.
   *
   * @param string[] $language_codes
   *   ISO 639-1 codes (e.g. en, fr).
   *
   * @return array<string, true>
   *   Casefolded stopword set.
   */
  public static function setForLanguages(array $language_codes = []): array {
    $codes = [];
    foreach ($language_codes as $code) {
      if (!is_string($code) || $code === '') {
        continue;
      }
      $code = strtolower($code);
      if (isset(self::LISTS[$code])) {
        $codes[$code] = $code;
      }
    }
    if ($codes === []) {
      $codes = ['en' => 'en'];
    }

    $key = implode(',', array_keys($codes));
    if (isset(self::$cache[$key])) {
      return self::$cache[$key];
    }

    $set = [];
    foreach ($codes as $code) {
      foreach (self::LISTS[$code] as $word) {
        $set[$word] = TRUE;
      }
    }
    return self::$cache[$key] = $set;
  }

  /**
   * Whether a token is a stopword for the given languages.
   *
   * @param string $token
   *   Already-normalized token.
   * @param string[] $language_codes
   *   ISO 639-1 codes.
   *
   * @return bool
   *   TRUE when the token should be ignored.
   */
  public static function isStopword(string $token, array $language_codes = []): bool {
    $set = self::setForLanguages($language_codes);
    return isset($set[mb_strtolower($token, 'UTF-8')]);
  }

